function stripProvincePrefix(value: string): string {
  return value
    .replace(/^IT-/i, '')
    .replace(/^provincia(\s+autonoma)?\s+(di\s+)?/i, '')
    .replace(/^citta\s+metropolitana\s+(di\s+)?/i, '')
    .replace(/^città\s+metropolitana\s+(di\s+)?/i, '')
    .trim()
}

export function isItalianProvinceCode(code: string): boolean {
  const upper = code.trim().toUpperCase()
  return CODE_SET.has(upper) || Boolean(LEGACY_CODES[upper])
}

/** Converte sigla, nome o alias nella sigla ISTAT. Vuoto se non riconoscibile. */
export function normalizeItalianProvince(raw: string | null | undefined): string {
  const value = stripProvincePrefix((raw ?? '').trim())
  if (!value) return ''
  const upper = value.toUpperCase()
  if (LEGACY_CODES[upper]) return LEGACY_CODES[upper]
  if (CODE_SET.has(upper) && upper.length === 2) return upper
  const paren = value.match(/\(([A-Za-z]{2})\)\s*$/)
  if (paren?.[1]) {
    const code = paren[1].toUpperCase()
    if (LEGACY_CODES[code]) return LEGACY_CODES[code]
    if (CODE_SET.has(code)) return code
  }
  const folded = foldProvinceKey(value)
  if (!folded) return ''
  if (folded.length === 2) {
    const asCode = folded.toUpperCase()
    if (LEGACY_CODES[asCode]) return LEGACY_CODES[asCode]
    if (CODE_SET.has(asCode)) return asCode
  }
  return NAME_TO_CODE.get(folded) ?? ''
}

export function normalizeAddressProvince(country: string, raw: string | null | undefined): string {
  const countryCode = country.trim().toUpperCase()
  if (countryCode === 'IT') return normalizeItalianProvince(raw)
  return (raw ?? '').trim().slice(0, 64)
}

export function isAddressProvinceValid(country: string, province: string): boolean {
  const countryCode = country.trim().toUpperCase()
  if (countryCode === 'IT') return Boolean(normalizeItalianProvince(province))
  return true
}

export function provinceFromAddressParts(country: string, ...candidates: Array<string | undefined>): string {
  for (const candidate of candidates) {
    const normalized = normalizeAddressProvince(country, candidate)
    if (normalized) return normalized
  }
  return ''
}
