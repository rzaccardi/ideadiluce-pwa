export type ItalianProvinceCode = (typeof ITALIAN_PROVINCES)[number]['code']

const CODE_SET = new Set<string>(ITALIAN_PROVINCES.map((row) => row.code))

/** Province soppresse (Sardegna 2016) ancora presenti su alcune anagrafiche Odoo. */
const LEGACY_CODES: Record<string, ItalianProvinceCode> = {
  CI: 'SU',
  VS: 'SU',
  OG: 'NU',
  OT: 'SS',
}

function foldProvinceKey(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[''`]/g, ' ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
}

const NAME_TO_CODE = new Map<string, string>()

for (const row of ITALIAN_PROVINCES) {
  NAME_TO_CODE.set(foldProvinceKey(row.code), row.code)
  NAME_TO_CODE.set(foldProvinceKey(row.name), row.code)
}

